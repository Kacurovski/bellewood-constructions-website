"""Build/check the library exclusively from the nine approved source folders.
Usage: python scripts/build_photo_library.py [--check]
Requires Pillow. Original filenames and EXIF never enter published assets.
"""
from pathlib import Path
from collections import Counter
from PIL import Image, ImageOps
import hashlib, json, sys
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/assets/project_photos'
OUT = ROOT / 'src/assets/projects/approved'
CATALOG = ROOT / 'scripts/photo-catalog.json'
FOLDERS = {'Ascot', 'Auchenflower', 'Bardon', 'Camp Hill', 'Clayfield', 'Kalinga', 'Wilston', 'Windsor', 'Yeronga'}
CROPS = [('bardon-joinery-detail', 'bardon-01', (.07,.4,.50,.9)), ('yeronga-window-detail', 'yeronga-03', (.01,.03,.43,.65))]
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
check = '--check' in sys.argv
catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
assert {row['folder'] for row in catalog} == FOLDERS
sources = {}
for folder in FOLDERS:
    actual = list((SOURCE/folder).glob('*.jpg'))
    expected = [row for row in catalog if row['folder'] == folder]
    assert Counter(digest(p) for p in actual) == Counter(row['sourceSha256'] for row in expected), f'Source inventory changed: {folder}; review the catalog before rebuilding'
    lookup = {digest(p): p for p in actual}
    for row in expected: sources[row['id']] = lookup[row['sourceSha256']]
if not check: OUT.mkdir(parents=True, exist_ok=True)
for row in catalog:
    target = OUT/(row['id']+'.webp')
    if check:
        assert target.is_file() and digest(target)==row['outputSha256'], f'Invalid derivative: {target.name}'
    else:
        with Image.open(sources[row['id']]) as original:
            image = ImageOps.exif_transpose(original).convert('RGB')
            image.thumbnail((2560,2560), Image.Resampling.LANCZOS)
            image.save(target, 'WEBP', quality=85, method=6)
        row['outputSha256'] = digest(target)
for name, source_id, box in CROPS:
    target = OUT/(name+'.webp')
    if check:
        assert target.is_file(), f'Missing crop: {name}'
    else:
        with Image.open(sources[source_id]) as original:
            image = ImageOps.exif_transpose(original).convert('RGB')
            image = image.crop(tuple(round(v*(image.width if i%2==0 else image.height)) for i,v in enumerate(box)))
            image.thumbnail((1200,1200), Image.Resampling.LANCZOS)
            image.save(target, 'WEBP', quality=87, method=6)
if not check:
    CATALOG.write_text(json.dumps(catalog, indent=2)+'\n', encoding='utf-8')
    lines = ["// Generated by scripts/build_photo_library.py from the approved source folders.", "import { photo } from './photos'", "import type { ImageSlot } from './projects'", "", "export const projectPhotos: Record<string, ImageSlot[]> = {"]
    for folder in sorted(FOLDERS):
        slug = folder.lower().replace(' ', '-')
        lines.append('  '+json.dumps(slug)+': [')
        for row in catalog:
            if row['folder']==folder: lines.append('    { src: photo('+json.dumps(row['id'])+'), alt: '+json.dumps(row['alt'])+' },')
        lines.append('  ],')
    lines.append('}\n')
    (ROOT/'src/data/photoLibrary.ts').write_text('\n'.join(lines), encoding='utf-8')
expected_names = {row['id']+'.webp' for row in catalog} | {name+'.webp' for name,_,_ in CROPS}
assert {p.name for p in OUT.iterdir()} == expected_names, 'Unexpected assets in the approved library'
print(f'{"Verified" if check else "Built"} {len(catalog)} photographs in {len(FOLDERS)} projects, plus {len(CROPS)} detail crops. Loose root files excluded.')
